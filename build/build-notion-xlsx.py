#!/usr/bin/env python3
"""Turn build/notion-sync.json into the china-notion-sync.xlsx workbook.

Regenerated by ./build.sh on every change — do not edit the workbook by hand, edits are lost.
"""
import json, os, sys
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = json.load(open(os.path.join(HERE, "notion-sync.json")))
OUT = os.path.join(os.path.dirname(HERE), "china-notion-sync.xlsx")

INK = "241F1B"; HEADBG = "241F1B"; HEADFG = "FBF8F3"
ACT = "F5E9CF"; PARK = "F6DED8"; MOVE = "E6EEE7"; ZEBRA = "FBF8F3"
thin = Side(style="thin", color="E9E1D4")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)

wb = Workbook()

def sheet(title, headers, rows, widths, fills=None, freeze="A2", wrap_cols=()):
    ws = wb.create_sheet(title)
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = Font(bold=True, color=HEADFG, size=10)
        cell.fill = PatternFill("solid", fgColor=HEADBG)
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[1].height = 30
    for i, r in enumerate(rows):
        ws.append(r)
        rowno = i + 2
        fill = fills(r) if fills else None
        for c in range(1, len(headers) + 1):
            cell = ws.cell(row=rowno, column=c)
            cell.border = BORDER
            cell.font = Font(size=10, color=INK)
            cell.alignment = Alignment(vertical="top", wrap_text=(c - 1) in wrap_cols)
            if fill:
                cell.fill = PatternFill("solid", fgColor=fill)
    for i, w in enumerate(widths):
        ws.column_dimensions[get_column_letter(i + 1)].width = w
    if freeze:
        ws.freeze_panes = freeze
    ws.auto_filter.ref = ws.dimensions
    return ws

# ---------------------------------------------------------------- README
ws = wb.active; ws.title = "README"
ws.column_dimensions["A"].width = 30; ws.column_dimensions["B"].width = 110
readme = [
    ("China trip — Notion propagation set", ""),
    ("", ""),
    ("What this is", "The reworked itinerary expressed as edits to make in Notion. Regenerated from the canvas on every "
                     "build, so it always matches what you approved. Notion itself has NOT been touched."),
    ("How it is produced", "build/generate-notion-sync.mjs diffs build/rebuilt.json (the agreed plan) against "
                           "build/viz-data.json (the current Notion snapshot). ./build.sh regenerates both this "
                           "workbook and the review canvas together."),
    ("Do not hand-edit", "Any edit made directly in this workbook is overwritten on the next build. Change the plan in "
                         "build/rebuild/<city>.json, rebuild, and this file follows."),
    ("", ""),
    ("SHEET: Changes", "START HERE. Only the stops that need a Notion edit, with the exact edit spelled out in the "
                       "Action column. If a day is fully agreed, working this sheet top-to-bottom is the whole job."),
    ("SHEET: Schedule", "The full agreed plan, every stop of every day, including the ones that need no change. "
                        "This is the reference for 'what should Notion look like when I am done'."),
    ("SHEET: Ideas (parked)", "Stops that were in Notion on a given day and no longer fit the reworked day. Keep the "
                              "Notion page — clear its day/time so it reads as an unscheduled idea. Nothing is deleted."),
    ("SHEET: Moves", "Stops that survive but on a different day. These are NOT cuts — only the day changes."),
    ("SHEET: Legs", "Every travel leg with mode, minutes, km and whether it is a real routed leg or the fitted "
                    "estimate. Use for the travel fields; the estimate is good to about +/-5 min, not exact."),
    ("", ""),
    ("Column -> Notion field", ""),
    ("  Activity", "the Notion page (place) name"),
    ("  Day / Date", "the Journey day the place hangs off"),
    ("  Order", "sort order within the day (x10 so you can insert between)"),
    ("  New Start / New End", "planned clock times; '(+1)' means after midnight, i.e. the following calendar day"),
    ("  New Duration (min)", "researched realistic dwell — a ceiling, not a target to squeeze"),
    ("  Travel to next ...", "mode / minutes / km from THIS stop to the next one; last stop of a day is the trip home"),
    ("", ""),
    ("Travel source", "'routed (real leg)' came from the real routed snapshot and wins over any model. "
                      "'estimated (fitted model)' is fitted from 258 real legs "
                      "(walk 5.3+18.26/km, metro 13.6+2.91/km, didi 6.6+1.50/km). "
                      "'co-located' is a genuine zero: a generic meal is eaten where you already are."),
    ("Known gap", "Notion's 'Book by' is empty for all 37 booking-required places, and 'Hours' is free prose filled "
                  "for only 46 of 366 places. Neither is reconstructed here."),
]
for i, (a, b) in enumerate(readme, start=1):
    ws.cell(row=i, column=1, value=a).font = Font(bold=(b == "" and a != ""), size=11 if i > 1 else 14, color=INK)
    c = ws.cell(row=i, column=2, value=b)
    c.alignment = Alignment(wrap_text=True, vertical="top"); c.font = Font(size=10, color=INK)

# ---------------------------------------------------------------- Changes / Schedule
SCH_H = ["City", "Day", "Date", "Order", "Activity", "Type", "New Start", "New End", "New Duration (min)",
         "Travel to next — to", "Mode", "Min", "Km", "Source",
         "Orig Day", "Orig Start", "Orig Duration (min)", "ACTION IN NOTION", "Duration basis", "Conf"]
SCH_W = [10, 5, 11, 6, 30, 10, 9, 9, 12, 26, 16, 6, 7, 22, 8, 9, 12, 40, 60, 6]

def schrow(r):
    return [r["city"], r["day"], r["date"], r["order"], r["activity"], r["kind"], r["newStart"], r["newEnd"],
            r["newDurMin"], r["toNext"], r["travelMode"], r["travelMin"], r["travelKm"], r["travelSource"],
            r["origDay"], r["origStart"], r["origDurMin"], r["action"], r["durBasis"], r["durConf"]]

sheet("Changes", SCH_H, [schrow(r) for r in DATA["changes"]], SCH_W,
      fills=lambda r: ACT, wrap_cols=(17, 18))
sheet("Schedule", SCH_H, [schrow(r) for r in DATA["schedule"]], SCH_W,
      fills=lambda r: (ACT if r[17] != "no change" else None), wrap_cols=(17, 18))

# ---------------------------------------------------------------- Ideas / Moves / Legs
sheet("Ideas (parked)",
      ["City", "Was on Day", "Date", "Activity", "Advice (min)", "ACTION IN NOTION", "Why it is parked"],
      [[i["city"], i["origDay"], i["date"], i["activity"], i["adviceMin"], i["action"], i["why"]] for i in DATA["ideas"]],
      [10, 11, 11, 30, 12, 52, 80], fills=lambda r: PARK, wrap_cols=(5, 6))

sheet("Moves",
      ["City", "Activity", "From Day", "To Day", "Advice (min)", "ACTION IN NOTION"],
      [[m["city"], m["activity"], m["fromDay"], m["toDay"], m["adviceMin"], m["action"]] for m in DATA["moves"]],
      [10, 30, 10, 9, 12, 44], fills=lambda r: MOVE, wrap_cols=(5,))

sheet("Legs",
      ["City", "Day", "Date", "From", "To", "Mode", "Minutes", "Km", "Source"],
      [[l["city"], l["day"], l["date"], l["from"], l["to"], l["mode"], l["minutes"], l["km"], l["source"]] for l in DATA["legs"]],
      [10, 5, 11, 30, 30, 9, 9, 8, 24])

wb.save(OUT)
print(f"notion workbook: {OUT} · {len(DATA['changes'])} changes · {len(DATA['schedule'])} stops · "
      f"{len(DATA['ideas'])} parked · {len(DATA['moves'])} moves · {len(DATA['legs'])} legs")
